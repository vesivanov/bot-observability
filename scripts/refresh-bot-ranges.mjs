#!/usr/bin/env node
/**
 * Regenerates src/lib/bot-ranges.generated.ts from the operators' own
 * published crawler ranges.
 *
 *   node scripts/refresh-bot-ranges.mjs
 *
 * Run monthly, or when a crawler starts recording `ua_only` hits that look real.
 * The lists change: OpenAI's ChatGPT-User list went from a few prefixes to 235
 * within a year, and Anthropic's grew from 4 entries to 14.
 */
import { writeFile } from "node:fs/promises";

const SOURCES = [
  { url: "https://openai.com/gptbot.json", bots: ["GPTBot"] },
  { url: "https://openai.com/searchbot.json", bots: ["OAI-SearchBot"] },
  { url: "https://openai.com/chatgpt-user.json", bots: ["ChatGPT-User"] },
  { url: "https://www.perplexity.ai/perplexitybot.json", bots: ["PerplexityBot"] },
  {
    url: "https://claude.com/crawling/bots.json",
    bots: ["ClaudeBot", "Claude-User", "Claude-SearchBot"],
  },
];

async function fetchRanges(url) {
  const res = await fetch(url, {
    headers: { "user-agent": "bot-observability-range-refresh/1.0" },
  });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  const json = await res.json();
  const prefixes = [];
  for (const p of json.prefixes ?? []) {
    if (p.ipv4Prefix) prefixes.push(p.ipv4Prefix);
    if (p.ipv6Prefix) prefixes.push(p.ipv6Prefix);
  }
  if (prefixes.length === 0) throw new Error(`${url} contained no prefixes`);
  return { prefixes, creationTime: json.creationTime ?? null };
}

const byBot = {};
const meta = {};
for (const { url, bots } of SOURCES) {
  const { prefixes, creationTime } = await fetchRanges(url);
  for (const bot of bots) {
    byBot[bot] = [...new Set([...(byBot[bot] ?? []), ...prefixes])].sort();
  }
  meta[url] = { creationTime, prefixes: prefixes.length };
  console.log(`${url}: ${prefixes.length} prefixes (source created ${creationTime})`);
}

const header = `// AUTO-GENERATED by scripts/refresh-bot-ranges.mjs — do not edit by hand.
// Regenerate with: node scripts/refresh-bot-ranges.mjs
//
// Operator-published lists, fetched ${new Date().toISOString().slice(0, 10)}:
${Object.entries(meta)
  .map(([url, m]) => `//   ${url} — ${m.prefixes} prefixes, created ${m.creationTime}`)
  .join("\n")}
//
// Anthropic publishes one list shared by all three of its crawlers, so a match
// proves "from Anthropic", not which Claude bot sent the request.
`;

const out = `${header}
export const BOT_RANGES: Record<string, string[]> = ${JSON.stringify(byBot, null, 2)};

export const BOT_RANGES_GENERATED_AT = "${new Date().toISOString()}";
`;

await writeFile("src/lib/bot-ranges.generated.ts", out);
const total = Object.values(byBot).reduce((n, v) => n + v.length, 0);
console.log(`wrote src/lib/bot-ranges.generated.ts — ${Object.keys(byBot).length} bots, ${total} prefixes`);
